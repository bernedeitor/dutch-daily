import { readFile, writeFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve, relative } from 'node:path';
const root = resolve(import.meta.dirname, '../docs');
async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const lists = await Promise.all(entries.map(e => e.isDirectory() ? walk(resolve(dir,e.name)) : [resolve(dir,e.name)]));
  return lists.flat();
}
const files = (await walk(root)).filter(p => !['sw.js','_headers','.nojekyll'].includes(relative(root,p))).sort();
const hash = createHash('sha256');
for (const file of files) { hash.update(relative(root,file)); hash.update(await readFile(file)); }
const version = hash.digest('hex').slice(0,16);
const assets = files.map(p => './' + relative(root,p).replaceAll('\\','/'));
const source = `// Generated by scripts/prepare.mjs. Re-run after editing any docs file.
const CACHE_NAME = 'dutch-daily-${version}';
const ASSETS = ${JSON.stringify(assets,null,2)};
const urls = ASSETS.map(path => new URL(path, self.registration.scope).href);
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    // Cache every required asset atomically before this version is usable.
    try { await cache.addAll(urls); }
    catch (error) { await caches.delete(CACHE_NAME); throw error; }
  })());
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key.startsWith('dutch-daily-') && key !== CACHE_NAME) await caches.delete(key);
    await self.clients.claim();
  })());
});
self.addEventListener('message', event => {
  if (event.data?.type === 'SKIP_WAITING') { self.skipWaiting(); return; }
  if (event.data?.type === 'CACHE_STATUS') event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    const matches = await Promise.all(urls.map(url => cache.match(url)));
    event.source?.postMessage({ type: 'CACHE_STATUS', ready: matches.every(Boolean), version: CACHE_NAME });
  })());
});
self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  const shell = new URL('./index.html', self.registration.scope).href;
  if (request.mode === 'navigate') {
    // A single cached shell also handles launch URLs containing queries.
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      return await cache.match(shell) || fetch(request);
    })());
    return;
  }
  if (!urls.some(asset => new URL(asset).pathname === url.pathname)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    return await cache.match(request, { ignoreSearch: true }) || fetch(request);
  })());
});
`;
await writeFile(resolve(root,'sw.js'),source);
console.log(`Prepared ${assets.length} offline assets · ${version}`);
